/* ============================================================================
 * MoongCheap ERD v2.2 — 완성본 DDL (PostgreSQL)
 * ----------------------------------------------------------------------------
 * 원본: MoongCheap_erd_v4.sql (ERDCloud export)
 *
 * [원본 대비 변경 사항]
 *  0. [결제·주문 파트 소유 테이블] 아래 5개는 컬럼명·NULL 제약·DEFAULT 를 원본
 *     그대로 두고, 타입만 PostgreSQL 규격에 맞게 정정했다.
 *       Payments / BrandpayPayMethod / PaymentsWebhock / Payout
 *       BrandPayToken
 *     정정 내역: LONG→BIGINT / STRING→VARCHAR(n)·TEXT / ENUM·EUNM→VARCHAR(30)
 *     ※ INT, BOOL, TIMESTAMP, JSON 은 PostgreSQL 유효 타입이므로 원본 그대로 둔
 *       곳이 있다 (각각 INTEGER, BOOLEAN, TIMESTAMP WITHOUT TIME ZONE, json 의 별칭)
 *     ※ 원본의 인라인 COMMENT '...' (MySQL 구문)는 SECTION 7 의
 *       COMMENT ON COLUMN 으로 이관했다.
 *
 *  1. (위 7개 제외) ERD 툴 의사 타입을 PostgreSQL 실제 타입으로 정규화
 *     LONG→BIGINT / STRING→VARCHAR·TEXT / INT→INTEGER / BOOL·EUNM 오타 수정
 *     ENUM→VARCHAR(30) (PostgreSQL ENUM 타입은 값 추가 시 마이그레이션 비용이
 *     크므로 VARCHAR + CHECK 로 대체. CHECK 는 파일 하단에 별도 블록으로 분리)
 *     TIMESTAMP→TIMESTAMPTZ (기존 TIMESTAMPTZ 컬럼과 혼용되어 있어 통일)
 *     JSON→JSONB
 *  2. PK 컬럼에 IDENTITY 부여 (원본은 채번 정의 없음)
 *     ※ 단, 아래 4개 테이블에는 IDENTITY 를 넣지 않았다. 애플리케이션에서 ID 를
 *       직접 발급해야 하며 JPA 의 @GeneratedValue(strategy = IDENTITY) 는 동작하지
 *       않는다.
 *       Payments / BrandpayPayMethod / PaymentsWebhock / Payout
 *  3. 백틱(`) → 큰따옴표(") — PostgreSQL 식별자. 대소문자 혼용 테이블명
 *     (Orders, GroupBuy, Payments 등)을 원본 그대로 보존하기 위해 인용 유지
 *  4. ERD 메모에 기재된 UNIQUE / INDEX 전량 생성
 *  5. 누락된 FOREIGN KEY 전량 추가 (원본은 4건만 존재)
 *  6. NULL 제약 수정 — 아래 [NULL 제약 수정 내역] 참조
 *
 * [NULL 제약 수정 내역]  ※ 근거: 기능정의서 구매자 MVP V1
 *  demand.desired_price_min/max   NULL → NOT NULL   희망 가격대 필수 입력
 *  demand.quantity                NULL → NOT NULL   수량 필수 (1~99)
 *  demand.desire_end_at           NULL → NOT NULL   유효기간 7일, 접수 시 확정
 *  demand.is_substitutable        NULL → NOT NULL DEFAULT FALSE
 *                                                   3-state 방지 (미동의=FALSE)
 *  demand.status                  NULL → NOT NULL DEFAULT 'UNASSIGNED'
 *                                                   partial index 조건 컬럼
 *  demand_board.sale_end_at       NULL → NOT NULL   보드 생성 시점 +5일 확정
 *  shipping_address.is_default    NULL → NOT NULL DEFAULT FALSE
 *                                                   partial unique 조건 컬럼
 *
 * [수정하지 않고 남겨둔 항목 — 별도 검토 필요]
 *  · product.demand_board_id NOT NULL
 *      여분 즉시판매(ON_SALE/SOLD_OUT) 건이 수요보드 없이 존재 가능하면 NULL 필요.
 *      B-04 바로구매 TBD 상태이므로 확정 후 조정.
 *  · demand_board.status DEFAULT 'OPEN'
 *      기능정의서 상태값은 GB_GATHERING / GB_ACTION_REQUIRED / GB_CLOSED /
 *      GB_CANCELED. 메모의 index 조건도 'OPEN' 기준이라 원본 유지했으나 통일 필요.
 *  · Orders.group_buy_id / brandpay_id / shipping_number NOT NULL
 *      바로구매(INSTANT) 주문, 일반결제 주문, 배송 시작 전 주문을 표현할 수 없음.
 *  · Payments / Payout / SellerPayoutAccount / PaymentsWebhock
 *      식별자·상태·금액 컬럼이 대부분 NULL 허용. 결제 파트 담당자 검토 영역.
 *  · GroupBuy
 *      target_count·count·group_buy_end_at·status 가 product·demand_board 와 중복.
 *
 * [스키마에 아직 반영되지 않은 기능정의서 요구사항]
 *  · demand : 자동결제 동의 기록(auto_payment_agreed_at) — FN-B09-02
 *  · demand : 결제수단 연결 여부 — 확정 인원 집계 기준 (FN-B09-02 / B-03·B-08)
 *  · demand : 대체상품 제안 사유(reason) — FN-B16-01 '유사 상품으로 묶인 이유'
 *  · shipping_address : no_entrance_code — FN-B30-02 '공동현관번호 없어요' 체크
 * ========================================================================== */


